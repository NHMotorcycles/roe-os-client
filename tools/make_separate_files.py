#!/usr/bin/env python3
"""Writes separate-files/ from join-roe-os.cmd: join-roe-os.ps1 (its PowerShell part) and two plain
launchers, join-roe-os.cmd (its batch part without the .ps1 copy of itself) and join-roe-os-window.cmd.
For virus scanners that flag the single file. Run it after every change of join-roe-os.cmd;
--check only compares (test_join.py does too)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'join-roe-os.cmd'
FOLDER = ROOT / 'separate-files'

PS1_HEADER = '''\
# join-roe-os.ps1: the PowerShell part of join-roe-os.cmd as a file of its own, for virus scanners
# that flag the single file. Keep join-roe-os.cmd and join-roe-os-window.cmd of this folder next to
# it and start one of them (join-roe-os-window.cmd: the window); they set what this code reads
# (ROE_JOIN_SELF, ROE_JOIN_CODE, ROE_JOIN_STEAM, ROE_JOIN_ARGS, ROE_JOIN_WINDOW).
# Generated from join-roe-os.cmd by tools/make_separate_files.py: change that file, not this one.
'''

# The batch part's .ps1 copy of itself becomes the .ps1 next to the launcher.
COPY = '''\
rem PowerShell runs a script file only when it ends in .ps1: this file's text as one in
rem %APPDATA%\\roe-join (type, not copy: copy would take a download's mark along, and PowerShell
rem would refuse it). The script removes older ones.
if not exist "%APPDATA%\\roe-join\\" mkdir "%APPDATA%\\roe-join"
set "ROE_JOIN_PS1=%APPDATA%\\roe-join\\run-%RANDOM%%TIME:~-2%%RANDOM%.ps1"
type "%~f0" > "%ROE_JOIN_PS1%" || goto :no_script
'''
NEXT_TO = '''\
rem The PowerShell code is join-roe-os.ps1 next to this file. Bypass: a downloaded .ps1 has the
rem download's mark, which RemoteSigned refuses. The window's Steam launch option names
rem join-roe-os-window.cmd.
set "ROE_JOIN_PS1=%~dp0join-roe-os.ps1"
set "ROE_JOIN_CODE=%~dp0join-roe-os.ps1"
set "ROE_JOIN_STEAM=%~dp0join-roe-os-window.cmd"
if not exist "%ROE_JOIN_PS1%" goto :no_script
'''
NO_SCRIPT = '''\
echo join-roe-os.cmd could not write its script into "%APPDATA%\\roe-join".
'''
MISSING = '''\
echo join-roe-os.ps1 is missing next to join-roe-os.cmd ("%~dp0"). Download join-roe-os.ps1,
echo join-roe-os.cmd and join-roe-os-window.cmd of separate-files into one folder.
'''

WINDOW = '''\
@echo off
rem join-roe-os-window.cmd: the window of join-roe-os.ps1 next to it (the separate files of
rem join-roe-os.cmd, for virus scanners that flag the single file). With arguments (Steam's launch
rem option "<this file>" --window %command%) it waits for the window, so Steam sees the game running
rem until it exits; the window hides this console itself.
rem Generated by tools/make_separate_files.py.
setlocal DisableDelayedExpansion
set "ROE_JOIN_SELF=%~f0"
set "ROE_JOIN_ARGS=%*"
set "ROE_JOIN_WINDOW=1"
rem Bypass: a downloaded .ps1 has the download's mark, which RemoteSigned refuses.
set "ROE_JOIN_PS1=%~dp0join-roe-os.ps1"
set "ROE_JOIN_CODE=%~dp0join-roe-os.ps1"
set "ROE_JOIN_STEAM=%~f0"
if not exist "%ROE_JOIN_PS1%" goto :no_script
if defined ROE_JOIN_ARGS (
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%ROE_JOIN_PS1%"
  exit /b 0
)
start "" /min powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%ROE_JOIN_PS1%"
exit /b 0
:no_script
echo join-roe-os.ps1 is missing next to join-roe-os-window.cmd ("%~dp0"). Download join-roe-os.ps1,
echo join-roe-os.cmd and join-roe-os-window.cmd of separate-files into one folder.
pause
exit /b 1
'''


def replace(text, old, new, count=1):
    if text.count(old) != count:
        raise SystemExit(f'join-roe-os.cmd changed: {old.splitlines()[0]!r} found {text.count(old)} times, expected {count}. Update tools/make_separate_files.py.')
    return text.replace(old, new)


def build(source):
    """The files of separate-files/ (name: bytes, CRLF) from join-roe-os.cmd's text."""
    text = source.replace('\r\n', '\n')
    head, mark, body = text.partition('\n#>\n')
    if not mark or not head.startswith('<# : '):
        raise SystemExit('join-roe-os.cmd has no batch part (<# : ... #>).')
    batch = head.split('\n', 1)[1] + '\n'
    batch = replace(batch, COPY, NEXT_TO)
    batch = replace(batch, '-ExecutionPolicy RemoteSigned', '-ExecutionPolicy Bypass', 3)
    batch = replace(batch, NO_SCRIPT, MISSING)
    batch = replace(batch, '@echo off\n', '@echo off\nrem join-roe-os.cmd of the separate files: runs join-roe-os.ps1 next to it, in a window or in this\n'
                    'rem console, as the single join-roe-os.cmd does. Generated by tools/make_separate_files.py.\n')
    files = {'join-roe-os.cmd': batch, 'join-roe-os-window.cmd': WINDOW, 'join-roe-os.ps1': PS1_HEADER + body}
    return {name: content.replace('\n', '\r\n').encode('ascii') for name, content in files.items()}


def main(argv):
    check = '--check' in argv
    wanted = build(SOURCE.read_bytes().decode('ascii'))
    stale = [name for name, data in wanted.items() if not (FOLDER / name).is_file() or (FOLDER / name).read_bytes() != data]
    extra = sorted(p.name for p in FOLDER.glob('*') if p.name not in wanted) if FOLDER.is_dir() else []
    if check:
        for name in stale:
            print(f'separate-files/{name} differs from join-roe-os.cmd: run tools/make_separate_files.py')
        for name in extra:
            print(f'separate-files/{name} is not made by tools/make_separate_files.py')
        return 1 if stale or extra else 0
    FOLDER.mkdir(exist_ok=True)
    for name in stale:
        (FOLDER / name).write_bytes(wanted[name])
        print(f'wrote separate-files/{name}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
